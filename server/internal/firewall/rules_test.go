// TestParseHandlesJumpLoop 验证链互相跳转时不会死循环。
//
// 手工维护的防火墙里出现 A→B→A 是常见的，解析器必须能收敛。
func TestParseHandlesJumpLoop(t *testing.T) {
	const loopDump = `*filter
:INPUT DROP [0:0]
:A - [0:0]
:B - [0:0]
-A INPUT -j A
-A A -j B
-A B -j A
-A B -p tcp --dport 1234 -j ACCEPT
COMMIT
`
	rules, err := ParseIPTablesSave(loopDump, "INPUT")
	if err != nil {
		t.Fatalf("解析失败: %v", err)
	}
	if len(rules) != 1 || rules[0].Port != 1234 {
		t.Fatalf("环状跳转下应恰好得到 1 条规则，got %+v", rules)
	}
}

// TestParseMissingChain 验证入口链不存在时如实报错。
func TestParseMissingChain(t *testing.T) {
	if _, err := ParseIPTablesSave("*filter\n:OUTPUT ACCEPT [0:0]\nCOMMIT\n", "INPUT"); err == nil {
		t.Fatal("入口链不存在时应返回错误")
	}
}

// TestParseNoPortRuleIsIgnored 验证「无 --dport 的 ACCEPT」不产出条目。
//
// 那种写法等价于「全部端口放行」，展开成六万条既没意义又会撑爆界面。
func TestParseNoPortRuleIsIgnored(t *testing.T) {
	const openDump = `*filter
:INPUT DROP [0:0]
-A INPUT -j ACCEPT
COMMIT
`
	rules, err := ParseIPTablesSave(openDump, "INPUT")
	if err != nil {
		t.Fatalf("解析失败: %v", err)
	}
	if len(rules) != 0 {
		t.Fatalf("全放行规则不应产出端口条目，got %+v", rules)
	}
}

func portKey(port int, proto string) string {
	return itoa(port) + "/" + proto
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var buf [8]byte
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	return string(buf[i:])
}

// TestNotExistErrOnlyClassifiesMissingObjects 覆盖「查不到被当成未启用」。
//
// 只有「链/表不存在」「守护进程没起来」能断定未启用。超时、权限不足
// 同样是非零退出，但它们说明的是「这次没读成」——按未启用上报的话，
// 界面会给出一个明确结论，而管理员会照着这个结论去排查规则。
func TestNotExistErrOnlyClassifiesMissingObjects(t *testing.T) {
	cases := []struct {
		msg  string
		want bool
	}{
		{"执行 iptables 失败: iptables: No chain/target/match by that name.", true},
		// iptables -C 检查 INPUT 跳转：规则不存在时是这条措辞，属于「确实没接入」。
		{"执行 iptables 失败: iptables: Bad rule (does a matching rule exist in that chain?).", true},
		{"执行 nft 失败: Error: No such file or directory", true},
		{"执行 firewall-cmd 失败: not running", true},
		{"执行 iptables 超时（可能 iptables 锁被占用）", false},
		{"执行 iptables 失败: Permission denied (you must be root)", false},
		{"执行 nft 失败: Operation not permitted", false},
	}
	for _, c := range cases {
		if got := notExistErr(errors.New(c.msg)); got != c.want {
			t.Errorf("notExistErr(%q) = %v，期望 %v", c.msg, got, c.want)
		}
	}
	if notExistErr(nil) {
		t.Error("nil 不该被判为「目标不存在」")
	}
}
