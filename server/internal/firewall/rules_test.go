func TestParseHandlesJumpLoop(t *testing.T) {
	const loopDump = `*filter
:INPUT DROP [0:0]
:A - [0:0]
:B - [0:0]
-A INPUT -j A
-A A -j B
-A B -j A
-A B -p tcp --dport 1234 -j ACCEPT
COMMIT
`
	rules, err := ParseIPTablesSave(loopDump, "INPUT")
	if err != nil {
		t.Fatalf("解析失败: %v", err)
	}
	if len(rules) != 1 || rules[0].Port != 1234 {
		t.Fatalf("环状跳转下应恰好得到 1 条规则，got %+v", rules)
	}
}

