// sampleDump 模拟一台真实服务器：放行规则分散在 INPUT 与被跳转的自定义链里。
const sampleDump = `# Generated by iptables-save
*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
:DOCKER - [0:0]
:DOCKER-USER - [0:0]
:IN_BT - [0:0]
:LT-TUNNEL - [0:0]
-A INPUT -p tcp --dport 22 -j ACCEPT
-A INPUT -j IN_BT
-A INPUT -j DOCKER-USER
-A INPUT -j DOCKER
-A INPUT -j LT-TUNNEL
-A INPUT -p icmp -j ACCEPT
-A DOCKER-USER -j RETURN
-A DOCKER -p tcp --dport 8080 -j ACCEPT
-A IN_BT -p tcp --dport 8888 -j ACCEPT
-A IN_BT -p tcp --dport 39000:39002 -j ACCEPT
-A LT-TUNNEL -p tcp --dport 20001 -j ACCEPT
-A LT-TUNNEL -p udp --dport 20002 -j ACCEPT
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
-A PREROUTING -p tcp --dport 9999 -j ACCEPT
COMMIT
`

// TestParseExpandsJumpChains 验证递归展开跳转链。
//
// 这是整个解析器的核心价值：只看 INPUT 会得出「只开了 22」的错误结论，
// 而真实的放行规则在 DOCKER / IN_BT / LT-TUNNEL 里。
func TestParseExpandsJumpChains(t *testing.T) {
	rules, err := ParseIPTablesSave(sampleDump, "INPUT")
	if err != nil {
		t.Fatalf("解析失败: %v", err)
	}

	got := make(map[string]string, len(rules)) // "port/proto" -> chain
	for _, r := range rules {
		got[portKey(r.Port, r.Proto)] = r.Chain
	}

	want := map[string]string{
		"22/tcp":    "INPUT",
		"8080/tcp":  "DOCKER",    // 经 INPUT -j DOCKER 到达
		"8888/tcp":  "IN_BT",     // 经 INPUT -j IN_BT 到达
		"20001/tcp": "LT-TUNNEL", // 面板托管
		"20002/udp": "LT-TUNNEL",
	}

	for k, chain := range want {
		gotChain, ok := got[k]
		if !ok {
			t.Errorf("缺少规则 %s（应来自 %s 链）", k, chain)
			continue
		}
		if gotChain != chain {
			t.Errorf("%s 的来源链错误：got %s, want %s", k, gotChain, chain)
		}
	}
}

// TestParseDoesNotLeakOtherTables 验证只解析 filter 表。
//
// nat 表里的 --dport 是「目的地址转换」而不是「入站放行」，
// 混进来会让管理员以为某个端口对外开放了。
func TestParseDoesNotLeakOtherTables(t *testing.T) {
	rules, err := ParseIPTablesSave(sampleDump, "INPUT")
	if err != nil {
		t.Fatalf("解析失败: %v", err)
	}
	for _, r := range rules {
		if r.Port == 9999 {
			t.Fatal("nat 表里的规则不应出现在入站放行列表中")
		}
	}
}

// TestParseExpandsPortRange 验证端口范围展开。
func TestParseExpandsPortRange(t *testing.T) {
	rules, err := ParseIPTablesSave(sampleDump, "INPUT")
	if err != nil {
		t.Fatalf("解析失败: %v", err)
	}

	for _, port := range []int{39000, 39001, 39002} {
		found := false
		for _, r := range rules {
			if r.Port == port && r.Proto == "tcp" && r.Chain == "IN_BT" {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("范围 39000:39002 应展开出端口 %d", port)
		}
	}
}

